"""Import CDC staff (from the cdc-staff sheet of CDC_lab.xlsx) into the database.

The sheet has been normalised into app/data/cdc_staff.json (one entry per email,
consistent branch codes, fixed usernames). The import is idempotent: running it
again updates existing people instead of duplicating them.

Rules:
* G-8 staff are central lab staff (LAB_STAFF, or SUPERVISOR for supervisors/QC).
* Everyone else is BRANCH_STAFF at their own branch (they create pickup requests).
* Credentials follow the existing pattern: password = username + "123".
"""
import json
import os
import re

from app import db
from app.models import Branch, StaffProfile, User
from app.utils.timezone import now_pkt

DATA_FILE = os.path.join(os.path.dirname(os.path.dirname(__file__)), 'data', 'cdc_staff.json')

# Canonical branches. `aliases` are names/codes this branch may already exist
# under (seed data, or codes generated by the old import_staff.py script).
BRANCHES = {
    'G8': {'name': 'G-8 Main Lab (HQ)', 'address': 'G-8 Markaz, Islamabad',
           'aliases': ['G8', 'G-8', 'G-8 Main Lab (HQ)', 'G8 Main Lab']},
    'WAH': {'name': 'Wah Branch', 'address': 'Wah Cantt', 'aliases': ['WAHBRANCH', 'Wah branch']},
    'I10': {'name': 'I-10 Branch', 'address': 'I-10, Islamabad', 'aliases': ['I-10']},
    'NGH': {'name': 'Noor General Hospital', 'address': 'Noor General Hospital',
            'aliases': ['NOORGENERA', 'Noor general hospital']},
    'IHSF10': {'name': 'IHS Hospital F-10', 'address': 'F-10, Islamabad',
               'aliases': ['IHSHOSPITA', 'IHS hospital F10']},
    'KAHUTA': {'name': 'CDC Kahuta', 'address': 'Kahuta', 'aliases': ['CDCKAHUTA', 'CDC kahuta']},
    'BLUEAREA': {'name': 'Blue Area Branch', 'address': 'Blue Area, Islamabad', 'aliases': ['Blue area']},
    'SHAHKHALID': {'name': 'Shah Khalid Branch', 'address': 'Shah Khalid Colony', 'aliases': ['Shah Khalid']},
    'INDUS': {'name': 'Indus Collection Point', 'address': 'Indus Hospital',
              'aliases': ['INDUSCOLLE', 'Indus Collection']},
    'HAYAT': {'name': 'Hayat Hospital', 'address': 'Hayat Hospital', 'aliases': ['HAYATHOSPI', 'Hayat hospital']},
    'MARDAN': {'name': 'CDC Mardan', 'address': 'Mardan', 'aliases': ['CDCMARDAN', 'Mardan', 'CDC Mardan']},
    'BUNER': {'name': 'CDC Buner', 'address': 'Buner', 'aliases': ['Buner']},
}


def password_for(username):
    return f"{username}123"


def load_staff():
    with open(DATA_FILE, encoding='utf-8') as fh:
        return json.load(fh)


def _find_branch(code):
    spec = BRANCHES[code]
    keys = [code] + spec['aliases'] + [spec['name']]
    for key in keys:
        branch = Branch.query.filter(Branch.code.ilike(key)).first() or \
                 Branch.query.filter(Branch.name.ilike(key)).first()
        if branch:
            return branch, False
    # No coordinates on purpose: wrong GPS would give wrong auto distances.
    branch = Branch(name=spec['name'], code=code, address=spec['address'])
    db.session.add(branch)
    db.session.flush()
    return branch, True


def _next_employee_id():
    highest = 3000
    for (emp_id,) in db.session.query(User.employee_id).all():
        match = re.match(r'EMP-(\d+)$', emp_id or '')
        if match:
            highest = max(highest, int(match.group(1)))
    return highest + 1


def import_cdc_staff(reset_passwords=True):
    """Create/update branches and staff accounts. Returns a summary dict.

    reset_passwords: set every imported account's password to the standard
    pattern (username + "123"), including accounts that already existed.
    """
    staff = load_staff()
    summary = {'created': 0, 'updated': 0, 'branches_created': [], 'accounts': []}
    branch_cache = {}
    next_emp = _next_employee_id()

    for person in staff:
        code = person['branch_code']
        if code not in branch_cache:
            branch, created = _find_branch(code)
            branch_cache[code] = branch
            if created:
                summary['branches_created'].append(branch.name)
        branch = branch_cache[code]

        user = User.query.filter(User.email.ilike(person['email'])).first()
        username = person['username']
        clash = User.query.filter(User.username == username).first()
        if clash and (user is None or clash.id != user.id):
            # Username already used by someone else: add a numeric suffix.
            n = 2
            while User.query.filter(User.username == f"{username}{n}").first():
                n += 1
            username = f"{username}{n}"

        if user is None:
            user = User(employee_id=f"EMP-{next_emp}", email=person['email'],
                        joining_date=now_pkt().date(), status=True)
            next_emp += 1
            db.session.add(user)
            summary['created'] += 1
            new_account = True
        else:
            summary['updated'] += 1
            new_account = False

        user.name = person['name']
        user.username = username
        user.role = person['role']
        user.branch_id = branch.id
        if new_account or reset_passwords:
            user.set_password(password_for(username))
        db.session.flush()

        profile = StaffProfile.query.filter_by(user_id=user.id).first()
        if profile is None:
            profile = StaffProfile(user_id=user.id)
            db.session.add(profile)
        profile.designation = person['designation']

        summary['accounts'].append({
            'name': person['name'], 'username': username,
            'password': password_for(username) if (new_account or reset_passwords) else '(unchanged)',
            'role': person['role'], 'branch': branch.name, 'designation': person['designation'],
        })

    db.session.commit()
    return summary
